// Same formatter settings as the zmanim app: ktfmt, Google style, 100 columns.
//   ./gradlew ktfmtFormat   rewrites Kotlin sources and build scripts
//   ./gradlew ktfmtCheck    fails if any file is not formatted (what CI runs)
allprojects {
  apply(plugin = "com.ncorti.ktfmt.gradle")
  configure<com.ncorti.ktfmt.gradle.KtfmtExtension> {
    googleStyle()
    maxWidth.set(100)
  }
  apply(plugin = "dev.detekt")
  configure<dev.detekt.gradle.extensions.DetektExtension> {
    config.setFrom(rootProject.file("config/detekt/detekt.yml"))
    buildUponDefaultConfig = true
    // Take every Kotlin directory under src/, whatever the module layout (commonMain,
    // androidMain..).
    source.setFrom(fileTree("src") { include("**/kotlin/**/*.kt") })
  }
  // The script tasks scan the whole project dir; keep them out of tool and VCS state.
  tasks.withType<com.ncorti.ktfmt.gradle.tasks.KtfmtBaseTask>().configureEach {
    exclude(".jj/**", ".git/**", ".gradle/**", ".kotlin/**", ".superpowers/**", "**/build/**")
  }
}

// iOS reads its version from iosApp/Configuration/Version.xcconfig, which is generated from
// version.properties so Android and iOS always agree. versionCode = major*1_000_000 + minor*1_000 +
// patch, the same rule as androidApp/build.gradle.kts.
val iosVersionFile = rootProject.file("iosApp/Configuration/Version.xcconfig")

fun iosVersionXcconfig(): String {
  val name =
    java.util
      .Properties()
      .apply { rootProject.file("version.properties").inputStream().use { load(it) } }
      .getProperty("versionName") ?: error("versionName missing from version.properties")
  val (major, minor, patch) = name.split('.').map { it.toInt() }
  return "// Generated by ./gradlew syncIosVersion from version.properties. Do not edit by hand.\n" +
    "MARKETING_VERSION=$name\n" +
    "CURRENT_PROJECT_VERSION=${major * 1_000_000 + minor * 1_000 + patch}\n"
}

tasks.register("syncIosVersion") {
  group = "versioning"
  description = "Writes iosApp/Configuration/Version.xcconfig from version.properties."
  doLast { iosVersionFile.writeText(iosVersionXcconfig()) }
}

tasks.register("checkIosVersion") {
  group = "versioning"
  description = "Fails if Version.xcconfig is out of date with version.properties."
  doLast {
    check(iosVersionFile.readText() == iosVersionXcconfig()) {
      "iosApp/Configuration/Version.xcconfig is out of date; run ./gradlew syncIosVersion"
    }
  }
}

package com.straphanger.app.data.basemap

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.IO
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import straphanger.shared.generated.resources.Res

/** A ring or line: longitude and latitude in degrees, interleaved (lng0, lat0, lng1, lat1, ...). */
class BasemapShape(val lngLat: DoubleArray) {
  val pointCount: Int
    get() = lngLat.size / 2
}

/** One borough's land: outer rings run anticlockwise and holes clockwise. */
class BasemapArea(val name: String, val rings: List<BasemapShape>)

/**
 * The map of New York City drawn under the subway lines, from NYC Open Data. Generated by
 * tools/basemap-import (composeResources/files/nyc_basemap.json).
 */
class NycBasemap(
  val sourceDate: String,
  val land: List<BasemapArea>,
  /** Park rings, oriented like [land]. */
  val parks: List<BasemapShape>,
  val highways: List<BasemapShape>,
  val arterials: List<BasemapShape>,
)

/** The file as written by tools/basemap-import: delta-encoded integer coordinates. */
@Serializable
private class BasemapFile(
  val version: Int,
  val sourceDate: String,
  val unitsPerDegree: Int,
  val land: List<LandAreaFile>,
  val parks: List<IntArray>,
  val highways: List<IntArray>,
  val arterials: List<IntArray>,
)

@Serializable private class LandAreaFile(val name: String, val rings: List<IntArray>)

object NycBasemapCatalog {

  const val BUNDLED_RESOURCE_PATH = "files/nyc_basemap.json"
  private const val SUPPORTED_VERSION = 1

  private val mutex = Mutex()
  private var cached: NycBasemap? = null

  /** Reads and parses the bundled basemap once; later calls return the same instance. */
  suspend fun loadBundled(): NycBasemap = mutex.withLock {
    cached
      ?: withContext(Dispatchers.IO) {
          parse(Res.readBytes(BUNDLED_RESOURCE_PATH).decodeToString())
        }
        .also { cached = it }
  }

  /**
   * Parses the generator's JSON. Throws [IllegalArgumentException] (which includes serialization
   * errors) for a file this version cannot read.
   */
  fun parse(json: String): NycBasemap {
    val file = Json.decodeFromString(BasemapFile.serializer(), json)
    require(file.version == SUPPORTED_VERSION) { "Unsupported basemap version ${file.version}" }
    require(file.unitsPerDegree > 0) { "unitsPerDegree must be positive" }
    fun decode(encoded: IntArray) = decodeShape(encoded, file.unitsPerDegree)
    return NycBasemap(
      sourceDate = file.sourceDate,
      land = file.land.map { area -> BasemapArea(area.name, area.rings.map(::decode)) },
      parks = file.parks.map(::decode),
      highways = file.highways.map(::decode),
      arterials = file.arterials.map(::decode),
    )
  }

  /** Undoes the generator's delta encoding: the first point absolute, then differences. */
  private fun decodeShape(encoded: IntArray, unitsPerDegree: Int): BasemapShape {
    require(encoded.size % 2 == 0) { "A basemap shape has an odd number of coordinates" }
    val out = DoubleArray(encoded.size)
    var lng = 0L
    var lat = 0L
    for (i in encoded.indices step 2) {
      lng += encoded[i]
      lat += encoded[i + 1]
      out[i] = lng.toDouble() / unitsPerDegree
      out[i + 1] = lat.toDouble() / unitsPerDegree
    }
    return BasemapShape(out)
  }
}
